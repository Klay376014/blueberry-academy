// Generates src/battle-only-formes.ts from @pkmn/dex, which is the same data
// Showdown itself runs on. Run it with `pnpm gen:battle-only-formes`.
//
// @pkmn/dex is a devDependency and is imported only here: the parser package
// ships the generated table, never the dex, so its `dependencies` stay empty.
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { Dex } from '@pkmn/dex'

const toID = (text) => text.toLowerCase().replace(/[^a-z0-9]+/g, '')

const entries = Dex.species
  .all()
  .filter((species) => species.exists && species.battleOnly)
  .map((species) => {
    const origins = Array.isArray(species.battleOnly) ? species.battleOnly : [species.battleOnly]
    return [toID(species.name), origins.map(toID)]
  })
  .sort(([a], [b]) => (a < b ? -1 : 1))

const body = entries.map(
  ([id, origins]) => `  ${id}: [${origins.map((o) => `'${o}'`).join(', ')}],`,
)

const file = `// Generated by scripts/generate-battle-only-formes.mjs — do not edit by hand.
// Run \`pnpm gen:battle-only-formes\` to regenerate it from @pkmn/dex.
//
// Every forme a Pokémon can only be in mid-battle, mapped to the formes it could
// have been registered as. A signature counts what a side brought, so any of
// these has to be read back to its origin or one Pokémon is counted twice.
//
// The mapping is not a suffix rule: Floette-Mega comes from Floette-Eternal and
// Greninja-Ash from Greninja-Bond, and Zygarde-Complete could be either Zygarde
// or Zygarde-10% — which is why the value is a list, resolved against the team
// the side actually registered.

export const BATTLE_ONLY_FORMES: Record<string, readonly string[] | undefined> = {
${body.join('\n')}
}
`

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'battle-only-formes.ts')
writeFileSync(out, file)
console.log(`wrote ${entries.length} formes to ${out}`)
